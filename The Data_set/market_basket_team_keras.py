# To remove unnecessary space from text
df["Product"] = df["Product"].astype(str).str.strip()
df["Product Category (Enhanced Ecommerce)"] = df["Product Category (Enhanced Ecommerce)"].astype(str).str.strip()
df["Transaction ID"] = df["Transaction ID"].astype(str).str.strip()

df["Product Category (Enhanced Ecommerce)"] = (df["Product Category (Enhanced Ecommerce)"].str.replace("&amp;", "&", regex=False))

# convert the revenue to number(removing $)
df["Product Revenue"] = (df["Product Revenue"].astype(str).str.replace(r"[$,]", "", regex=True).astype(float))

df["Product Revenue"].head()

df.info()

df.head(7)

# creating new transcation date for training
transaction_data = (df.groupby("Transaction ID")
    .agg(
        total_products=("Product", "nunique"),
        total_units=("Unique Purchases", "sum"),
        total_revenue=("Product Revenue", "sum"),
        categories=("Product Category (Enhanced Ecommerce)", "nunique")
    )
    .reset_index()
)

transaction_data.head()

transaction_data.shape

transaction_data.describe()

transaction_data.isnull().sum()

# then we perform future scaling
features = [ "total_products","total_units","total_revenue","categories"]

X = transaction_data[features]

X.head()

scaler = StandardScaler()

X_scaled = scaler.fit_transform(X)

X_scaled[:5]

kmeans = KMeans( n_clusters=2,random_state=42,n_init=10)

kmeans.fit(X_scaled)

inertias, sil_scores = [], []
for k in range(2,11):
    kmeans = KMeans(n_clusters=k, random_state=42, n_init=10)
    kmeans.fit(X_scaled)
    inertias.append(kmeans.inertia_)
    sil_scores.append(silhouette_score(X_scaled, kmeans.labels_, sample_size=1000, random_state=42))

for k, i, s in zip(range(2,11), inertias, sil_scores):
    print(f"K: {k}, Inertia: {i:.2f}, Silhouette Score: {s:.3f}")

best_k = range(2, 11)[int(np.argmax(sil_scores))]
print("Best K by silhouette:", best_k)

final_kmeans = KMeans(n_clusters=best_k, random_state=42, n_init=10)
transaction_data["cluster"] = final_kmeans.fit_predict(X_scaled)
transaction_data.head()

cluster_summary = transaction_data.groupby("cluster")[["total_products", "total_units", "total_revenue", "categories"]].mean()
